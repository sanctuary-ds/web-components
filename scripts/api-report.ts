import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

interface PackageJson {
  name: string;
  customElements?: string;
  sideEffects?: string[] | boolean;
  peerDependencies?: Record<string, string>;
  exports?: Record<string, unknown>;
}

interface CemDeclaration {
  kind: string;
  name: string;
  customElement?: boolean;
  tagName?: string;
  attributes?: Array<{ name: string; type?: { text: string } }>;
  members?: Array<{
    kind: string;
    name: string;
    privacy?: string;
    static?: boolean;
    type?: { text: string };
  }>;
  events?: Array<{ name: string; type?: { text: string } }>;
  slots?: Array<{ name: string }>;
  cssParts?: Array<{ name: string }>;
  cssProperties?: Array<{ name: string; default?: string }>;
}

interface CemModule {
  path: string;
  declarations?: CemDeclaration[];
  exports?: Array<{ kind: string; name: string }>;
}

interface CemManifest {
  schemaVersion: string;
  modules?: CemModule[];
}

const root = resolve(import.meta.dirname, "..");
const reportPath = resolve(root, "api/web-components.api.txt");

function formatExports(exportsField: Record<string, unknown> | undefined): string[] {
  if (!exportsField) {
    return [];
  }

  return Object.entries(exportsField)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([subpath, target]) => {
      if (typeof target === "string") {
        return `  ${subpath} -> ${target}`;
      }
      const record = target as Record<string, string>;
      const entries = Object.entries(record)
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([k, v]) => `${k}: ${v}`)
        .join(", ");
      return `  ${subpath} -> { ${entries} }`;
    });
}

function buildReport(): string {
  const pkg = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8")) as PackageJson;
  const cem = JSON.parse(
    readFileSync(resolve(root, "custom-elements.json"), "utf8"),
  ) as CemManifest;

  const lines: string[] = [
    `# Public API report for ${pkg.name}`,
    "# Generated by scripts/api-report.ts; do not edit by hand.",
    "",
    "## Package exports",
    ...formatExports(pkg.exports),
    "",
    "## Package metadata",
    `  customElements: ${pkg.customElements ?? "(none)"}`,
    `  sideEffects: ${JSON.stringify(pkg.sideEffects ?? true)}`,
  ];

  const peers = Object.entries(pkg.peerDependencies ?? {}).sort(([a], [b]) => a.localeCompare(b));
  if (peers.length > 0) {
    lines.push("  peerDependencies:");
    for (const [name, range] of peers) {
      lines.push(`    ${name}: ${range}`);
    }
  }

  lines.push("", "## Exported declarations");

  const modules = [...(cem.modules ?? [])]
    .filter((mod) => !mod.path.startsWith("src/internal/"))
    .sort((a, b) => a.path.localeCompare(b.path));
  for (const mod of modules) {
    const publicExports = [...(mod.exports ?? [])]
      .map((entry) => `${entry.kind}:${entry.name}`)
      .sort((a, b) => a.localeCompare(b));
    if (publicExports.length === 0) {
      continue;
    }

    lines.push(`  ${mod.path}: ${publicExports.join(", ")}`);
  }

  const elements = modules
    .flatMap((mod) => mod.declarations ?? [])
    .filter((decl) => decl.customElement && decl.tagName)
    .sort((a, b) => (a.tagName ?? "").localeCompare(b.tagName ?? ""));

  lines.push("", "## Custom elements");
  if (elements.length === 0) {
    lines.push("  (none yet — foundation phase)");
  } else {
    for (const el of elements) {
      lines.push(`  <${el.tagName}> (${el.name})`);
      for (const attr of [...(el.attributes ?? [])].sort((a, b) => a.name.localeCompare(b.name))) {
        lines.push(`    attr ${attr.name}${attr.type?.text ? `: ${attr.type.text}` : ""}`);
      }
      for (const ev of [...(el.events ?? [])].sort((a, b) => a.name.localeCompare(b.name))) {
        lines.push(`    event ${ev.name}${ev.type?.text ? `: ${ev.type.text}` : ""}`);
      }
      for (const slot of [...(el.slots ?? [])].sort((a, b) => a.name.localeCompare(b.name))) {
        lines.push(`    slot ${slot.name || "(default)"}`);
      }
      for (const part of [...(el.cssParts ?? [])].sort((a, b) => a.name.localeCompare(b.name))) {
        lines.push(`    part ${part.name}`);
      }
      for (const prop of [...(el.cssProperties ?? [])].sort((a, b) =>
        a.name.localeCompare(b.name),
      )) {
        lines.push(`    cssprop ${prop.name}${prop.default ? ` = ${prop.default}` : ""}`);
      }
    }
  }

  return `${lines.join("\n")}\n`;
}

const checkOnly = process.argv.includes("--check");
const generated = buildReport();

if (checkOnly) {
  let existing = "";
  try {
    existing = readFileSync(reportPath, "utf8");
  } catch {
    console.error("Missing api/web-components.api.txt. Run `pnpm run api` to generate it.");
    process.exit(1);
  }

  if (existing !== generated) {
    console.error("Public API report is out of date. Run `pnpm run cem && pnpm run api`.");
    process.exit(1);
  }

  console.log("Public API report matches current package exports and CEM.");
} else {
  mkdirSync(dirname(reportPath), { recursive: true });
  writeFileSync(reportPath, generated, "utf8");
  console.log("Updated api/web-components.api.txt.");
}
